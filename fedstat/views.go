package fedstat

import "github.com/kmlebedev/clickhouse-import-rosstat/util"

// fedstatWeeklyPricesView — long-форма витрины (стандарт §10.3). region — часть
// ряда: 2008–2022 и 2026 — разные определения РФ, и складывать их в одну линию
// без оговорки нельзя. Единица измерения — в series (название товара), значение —
// рубли.
var fedstatWeeklyPricesView = util.View{
	Name:   "v_fedstat_weekly_prices",
	Tables: []string{fedstatTable},
	Select: `SELECT 'fedstat' AS source, product AS series, region, date, toFloat64(price) AS value
FROM fedstat_weekly_prices FINAL`,
	Comment: "ЕМИСС 37426: еженедельные средние потребительские цены (тарифы) на отдельные товары и услуги, рубли. 2008–2022 — Российская Федерация (s_OKATO=643); 2026 недели 39–40 — Российская Федерация без учёта новых субъектов (s_OKATO=643004.АГ). 2023–2025 в источнике отсутствуют. Значение — уровень цены, не индекс; единица измерения — в названии ряда. Перед расчётом читать v_series_catalog по (source='fedstat', series)",
	Columns: map[string]string{
		"source": "Источник данных: всегда fedstat",
		"series": "Товар/услуга; совпадает с series в v_series_catalog. Единица измерения (кг, л, шт., месяц с человека и т.п.) — в названии ряда",
		"region": "Определение РФ: 'Российская Федерация' — 2008–2022; 'Российская Федерация без учета новых субъектов (с 01.01.2023)' — 2026 недели 39–40. Это разные территориальные определения, сравнивать ряды между регионами без оговорки нельзя",
		"date":   "Дата регистрации цен (понедельник недели). 2008–2022 — недельные даты; 2026 — 39-я и 40-я недели (2026-10-05 и 2026-10-12)",
		"value":  "Средняя потребительская цена, рублей за единицу измерения из series. Уровень цены, не индекс: изменение за n недель = value_t / value_{t−n} − 1",
	},
}
