// Package archive хранит версии файлов источников: одна версия файла — один объект в хранилище
// плюс строка реестра увиденных версий. Нужен потому, что выгрузки источников обновляются реже
// прогонов конвейера: после публикации новой версии прежняя с сайта исчезает, и восстановить по
// ней ряд (или объяснить расхождение в витрине) уже нечем. Архив не дублирует данные — истина о
// рядах остаётся в ClickHouse; архив отвечает только на вопрос «что именно импортировали тогда».
package archive

import (
	"context"
	"errors"
)

// ErrAuth — токен не принят (401): отозван, истёк или выдан без нужного scope. Отдельный
// sentinel, а не текст: действие дежурного по логу другое, чем при квоте, — обновить токен.
// Обёртывается через %w, поэтому проверяется errors.Is, а не сравнением строк.
var ErrAuth = errors.New("archive: токен не принят (401)")

// ErrQuota — квота или лимит хранилища (403/413/423/507): место кончилось либо файл больше
// разрешённого. Второй различимый случай (спека §3.3): «токен» и «квота» требуют разных действий.
var ErrQuota = errors.New("archive: квота или лимит хранилища (403/413/423/507)")

// Store — объектное хранилище версий файлов. Контракт минимален под два бэкенда: Яндекс.Диск
// (upload/download/resources) сегодня и S3 (PutObject/GetObject/HeadObject) — потом; вызывающему
// нужны ровно три операции — записать байты, прочитать их и спросить наличие. Ключи относительные,
// с «/»-разделителями; корень навешивает бэкенд, поэтому смена хранилища или его каталога не
// меняет ключи (и не расходится с ними реестр).
type Store interface {
	// Name — "local" | "yandex": попадает в логи и реестр, чтобы по записи было видно бэкенд.
	Name() string
	// Put записывает версию целиком (ключ и есть версия: второй Put того же ключа — не ошибка).
	Put(ctx context.Context, key string, body []byte) error
	// Get отдаёт байты версии: реестр, тесты и восстановление из архива — названный follow-up
	// этого пункта (спека §1.3), ради которого объекты и хранятся целиком, а не хешами.
	Get(ctx context.Context, key string) ([]byte, error)
	// Exists — есть ли версия. Единственная операция префлайта на no-op-пути: «версия известна, но
	// не в архиве» проверяется без чтения реестра и без ClickHouse (спека §3.2).
	Exists(ctx context.Context, key string) (bool, error)
}
