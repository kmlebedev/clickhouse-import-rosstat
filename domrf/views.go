package domrf

import "github.com/kmlebedev/clickhouse-import-rosstat/util"

// domrfMortgageView — витрина long-формы обоих рядов пакета: месячный рынок и недельные ставки.
// Источники записаны в двух полях по-разному — ровно как в v_bank_macro: Tables — константами
// пакета (util.CreateView проверяет по ним наличие таблиц), а Select — литералами: витрина
// публичный контракт для агента, и переименование константы пакета не должно молча уводить её к
// другой таблице.
//
// Единицы рядов разные и не пересчитываются: млн руб., единиц, тыс. руб., доля, % годовых,
// индекс — читать v_series_catalog по (source, series). Ставка в v_bank_macro (domrf_mortgage,
// пакет bank/) хранится долей, здесь — проценты: смешивать два источника в одном запросе нельзя.
var domrfMortgageView = util.View{
	Name:   "v_domrf_mortgage",
	Tables: []string{domrfMarketTable, domrfWeeklyTable},
	Select: `SELECT 'domrf_mortgage_market' AS source, series, date, toFloat64(value) AS value FROM domrf_mortgage_market FINAL
UNION ALL SELECT 'domrf_mortgage_weekly', product, date, toFloat64(rate) FROM domrf_mortgage_weekly FINAL`,
	Comment: "Рынок ипотеки ДОМ.РФ: месячные ряды (выдачи, ДДУ, портфель, просрочка, ставки; 2006-01 … 2026-09) " +
		"и недельные ставки предложения топ-20 банков по продуктам (2021-09 … 2026-10). Единицы разные — " +
		"читать v_series_catalog по (source, series). Ставки здесь в процентах годовых; унаследованная " +
		"domrf_mortgage в v_bank_macro хранит долю (0.187 = 18,7 %) — два источника не смешивать",
	Columns: map[string]string{
		"source": "Набор: domrf_mortgage_market — месячный рынок (лист «общая таблица_помесячно»), domrf_mortgage_weekly — недельная ставка предложения по продуктам",
		"series": "Ряд из каталога: у месячного набора — код из кода импортёра (issued_volume_ddu, rate_primary, …), у недельного — продукт источника (Новостройка, Семейная ипотека, …)",
		"date":   "Дата точки: у месячных рядов — первое число отчётного месяца (ставки выдачи — за месяц), у недельных — дата недельного среза (пятница)",
		"value":  "Значение в единице ряда: млн руб., единиц, тыс. руб., доля (0…1), % годовых — см. unit в v_series_catalog",
	},
}

// domrfPriceIndexView — панель индекса цен первички: регион × разрез по комнатам × месяц, с
// числом сделок ДДУ. Это не long-форма: у точки три значимых измерения, и agent читает её
// фильтрами по региону и разрезу, а не по имени ряда.
var domrfPriceIndexView = util.View{
	Name:   "v_domrf_price_index",
	Tables: []string{domrfPriceIndexTable},
	Select: `SELECT region, room_count, date, index_value, index_diff_month, deals FROM domrf_price_index FINAL`,
	Comment: "Индекс цен на первичном рынке жилья ДОМ.РФ (100 = январь 2021) по регионам и разрезам " +
		"по комнатам, с числом сделок ДДУ за месяц: 2021-01 … 2026-09, 75 регионов. Строка «Российская " +
		"Федерация» — агрегат, равный сумме субъектов: не складывать с субъектами повторно. room_count=all — " +
		"агрегат по всем квартирам, а не сумма разрезов 1/2/3",
	Columns: map[string]string{
		"region":           "Регион источника: «Российская Федерация» (агрегат), субъекты, «Город Москва», «Город Санкт-Петербург»",
		"room_count":       "Разрез: all — все квартиры (агрегат), 1/2/3 — число комнат. Разреза «студия» источник не отдаёт: запрос студии молча сводится к all",
		"date":             "Первое число отчётного месяца",
		"index_value":      "Индекс цен первички, 100 = январь 2021 (201.83 у РФ в 2026-09). Уровень, не темп",
		"index_diff_month": "Изменение индекса к предыдущему месяцу, % (как в источнике; у января 2021 — 0)",
		"deals":            "Число сделок ДДУ за месяц в регионе (у агрегата РФ — сумма субъектов). Экспортная выгрузка источника даёт другую выборку (≈ +7 %), поэтому не смешивать с /export/deals/",
	},
}
