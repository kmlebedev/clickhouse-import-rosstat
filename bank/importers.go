package bank

import "github.com/kmlebedev/clickhouse-import-rosstat/chimport"

// bankImporter — запись реестра импортёров пакета: сам импортёр, таблица, в которую
// он пишет, и запрос количественного чека версии (префлайта). Регистрируются
// значения импортёров пакета как есть (шесть шаблонных и внутренний маппер
// &BankCompanyMetrics{}), а не обёртки: Name() и Import() — их собственные, а
// производные (каталог рядов, витрины) публикует шаблон util.ClickHouseImport через
// поле AfterImport. Полей table и countPoints не видит никто, кроме теста
// TestBankImportersNamedAndRegistered: по ним проверяется, что импортёр занимает
// таблицу утверждённого набора (О1) и что объявленный в реестре префлайт совпадает с
// объявлением самого импортёра (Publication()).
type bankImporter struct {
	chimport.ImportStat
	table string
	// countPoints — литерал PublicationCountPoints импортёра ("" — префлайта нет).
	// Литерал, а не метод Publication(): именно расхождение этих двух источников
	// значения и обязан ловить тест реестра.
	countPoints string
}

// bankImporters — единственная точка регистрации импортёров пакета: персональных
// init()-append по файлам импортёров больше нет (семь записей в одном месте). Порядок
// повторяет dagu/bank.yaml; в chimport.Stats порядок значения не имеет. tbank_group_ifrs
// стоит последним из импортёров и вне расписания (О2) — шага в dagu/bank.yaml у него
// нет; маппер bank_company_metrics идёт последней записью, как и последним шагом
// расписания (спека §3.8).
//
// Таблицы записаны литералами намеренно. Префикса пакета у банка нет (О1: имена
// шести таблиц утверждены владельцем как есть — они уникальны в репозитории и уже
// несут источник), поэтому тавтологию держит литеральный набор, а не префикс: ссылка
// на константу импортёра (например, sberCSITable) сделала бы проверку тавтологичной
// — тест сравнивал бы константу с самой собой, тогда как литерал падает ровно на
// переименовании таблицы в имя вне утверждённого набора, то есть на правке, которая
// увела бы витрину v_bank_macro к чужим данным. Литералы сверены с константами кода
// при переносе регистрации.
//
// bank_company_metrics — седьмая запись с таблицей вне набора: внутренний маппер
// пишет курированные метрики Сбера и ВТБ в общую company_financials (её же ведут
// polyus/import.go и views/company.go), а не в свою таблицу. У него Name() отличается
// от имени таблицы, поэтому в реестре он записан раздельно (прецедент — cbr_mp_survey
// и cbr_mo_br в общей macro_series).
//
// Колонка countPoints — запрос количественного чека версии у импортёров, у которых
// точка контроля публикации объявлена (спека §3.1); пустая строка — префлайта нет.
// Литералы и здесь: запрос — часть утверждения «эти точки мои» (FINAL), и тест
// реестра сверяет их с объявлением импортёра (Publication().CountPoints) — двумя
// независимыми записями одного утверждения. Незамеченная правка запроса в объявлении
// оставила бы реестр описывающим другой чек, а забытое объявление молча выключило бы
// префлайт.
//
// Префлайта нет у четырёх записей, и у каждой это осознанно: у
// sber_consumper_spending_index и sber_izmenenie_trat HEAD источника отвечает 403, а
// отпечаток версии построить нельзя (спека §4.2, стандарт §9.3); у tbank_group_ifrs
// объявлять чек не на чем — ссылка ведёт на PDF и импорт падает до разбора (О2, О4);
// у bank_company_metrics внешнего артефакта нет вовсе — он читает уже импортированные
// таблицы пакета. У rus_vtb_group_ifrs объявление есть, но решением о no-op оно не
// служит: артефакт — набор файлов по отчётным периодам, и «что уже разобрано» решает
// гейт пофайловых версий (О3) — объявление включает архив версий и строки
// source_publications (стандарт §9.6).
var bankImporters = []bankImporter{
	{sberFinRezImporter, "sber_finansovie_rezultaty", "SELECT count() FROM sber_finansovie_rezultaty FINAL"},
	{sberCSIImporter, "sber_consumper_spending_index", ""},
	{sberCSIWeekImporter, "sber_izmenenie_trat", ""},
	{vtbImporter, "rus_vtb_group_ifrs", "SELECT count() FROM rus_vtb_group_ifrs FINAL"},
	{domrfImporter, "domrf_mortgage", "SELECT count() FROM domrf_mortgage FINAL"},
	{tbIfrsImporter, "tbank_group_ifrs", ""},
	{&BankCompanyMetrics{}, "company_financials", ""},
}

// init — единственная регистрация импортёров пакета в chimport.Stats. Порядок
// append совпадает с порядком реестра; main.go запускает всех (или фильтрует по
// CLICKHOUSE_IMPORT_STAT=Name()).
func init() {
	for _, imp := range bankImporters {
		chimport.Stats = append(chimport.Stats, imp)
	}
}
