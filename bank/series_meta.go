// afterBankMacro — производные импортёров пакета (образец rosstat/series_meta.go): каталог рядов и
// обе витрины публикуются шаблоном после Send точек и до записи строки версии (стандарт §5.2,
// §10.2). Каталог — общий для пяти импортёров (bankSeriesMeta): каждый прогон перезаписывает все
// описания (ReplacingMergeTree по (source, series)), поэтому каталог сходится и когда в расписании
// отработал только один импортёр. Витрины тоже общие: util.CreateView пропускает витрину, пока не
// существует каждой её таблицы, поэтому прогон одного импортёра чужую витрину не создаёт и не
// ломает.
//
// Точки контроля публикации есть у трёх импортёров из пяти (sber_finansovie_rezultaty,
// rus_vtb_group_ifrs, domrf_mortgage): сбой публикации оставляет версию незаписанной, и обычный
// импортёр следующим прогоном повторяет полный путь, а не уходит в no-op с устаревшим каталогом.
// У ВТБ полный путь повторяет гейт пофайловых версий, поэтому производные его no-op-путей
// перепубликует собственный Import() (стандарт §5.2, урок rosstat_ipc_weeks_bulletins); у двух
// наборов СберИндекса префлайта нет вовсе (спека §4.2) — каждый прогон идёт полным путём.
func afterBankMacro(meta []util.SeriesMeta) func(context.Context, driver.Conn) error {
	return func(ctx context.Context, conn driver.Conn) error {
		if err := util.UpsertSeriesCatalog(ctx, conn, meta); err != nil {
			return err
		}
		if _, err := util.CreateView(ctx, conn, sberSpendingView); err != nil {
			return err
		}
		_, err := util.CreateView(ctx, conn, bankMacroView)
		return err
	}
}

