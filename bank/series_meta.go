// afterSberMacro — производные импортёров Сбера (образец rosstat/series_meta.go): каталог рядов и
// общая витрина обоих наборов публикуются после Send точек и до записи строки версии (стандарт
// §5.2, §10.2). Сбой публикации оставляет версию незаписанной, и следующий прогон повторяет
// полный путь, а не уходит в no-op без каталога и витрины у агента.
//
// Каталог — общий для двух импортёров (sberSeriesMeta): каждый прогон перезаписывает все 51
// описание (ReplacingMergeTree по (source, series)), поэтому каталог сходится и когда в расписании
// отработал только один набор. Витрина — тоже общая: util.CreateView пропускает её, пока нет
// второй таблицы, поэтому прогон одного импортёра витрину не создаёт и не ломает.
func afterSberMacro(meta []util.SeriesMeta) func(context.Context, driver.Conn) error {
	return func(ctx context.Context, conn driver.Conn) error {
		if err := util.UpsertSeriesCatalog(ctx, conn, meta); err != nil {
			return err
		}
		_, err := util.CreateView(ctx, conn, sberSpendingView)
		return err
	}
}

