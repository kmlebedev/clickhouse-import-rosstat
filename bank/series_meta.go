// sberWeekSeriesMeta — 46 описаний недельных рядов. Собирается циклом: описания различаются
// только именем категории и оговоркой для агрегатов (образец — rosstat/ipcWeeksSeriesMeta), а
// список имён вынесен в sberWeekCategories, чтобы контракт каталога на фикстуре был обозримым.
var sberWeekSeriesMeta = buildSberWeekSeriesMeta()

func buildSberWeekSeriesMeta() []util.SeriesMeta {
	meta := make([]util.SeriesMeta, 0, len(sberWeekCategories))
	for _, category := range sberWeekCategories {
		description := fmt.Sprintf(sberWeekDescriptionFormat, category)
		if note := sberWeekAggregateNotes[category]; note != "" {
			description += " " + note
		}
		meta = append(meta, util.SeriesMeta{
			Source:      sberSourceWeek,
			Series:      category,
			Title:       fmt.Sprintf("Изменение потребительских расходов, %s, недельно, %% г/г", category),
			Unit:        "% к сопоставимой ISO-неделе прошлого года (положительное — рост)",
			Frequency:   "W",
			Origin:      sberWeekOrigin,
			Description: description,
		})
	}
	return meta
}

