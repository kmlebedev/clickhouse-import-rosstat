// buildBankSourceMeta собирает описания рядов источника: Title — заголовок по шаблону (%s — имя
// ряда), Frequency — «M», когда у группы не задана своя (недельные ряды СберИндекса идут мимо
// этой функции своим циклом). В шаблоне заголовка, кроме %s, знаков процента быть не должно: их
// съел бы Sprintf, и в каталоге у агента оказался бы мусор формата, а не фраза.
func buildBankSourceMeta(source, titleFormat string, groups []bankSourceGroup) []util.SeriesMeta {
	var meta []util.SeriesMeta
	for _, g := range groups {
		frequency := g.Frequency
		if frequency == "" {
			frequency = "M"
		}
		for _, name := range g.Names {
			meta = append(meta, util.SeriesMeta{
				Source:      source,
				Series:      name,
				Title:       fmt.Sprintf(titleFormat, name),
				Unit:        g.Unit,
				Frequency:   frequency,
				Origin:      g.Origin,
				Description: g.Description,
			})
		}
	}
	return meta
}

