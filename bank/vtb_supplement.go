// Разбор квартальных супердополнений ВТБ (financial_data_supplement_<ММГГ>_rus.xlsx) — второй
// семьи артефактов импортёра rus_vtb_group_ifrs (спека 2026-11-04). Разбирается только лист
// «1.Ключевые показатели»: пять секций со своими строками-шапками (P&L и коэффициенты — с
// колонками-периодами «9М'26»/«3кв'26», баланс, качество кредитов и достаточность капитала — с
// колонками-датами серийными номерами Excel). Полные формы («2.P&L», «3.Баланс ») в объём не
// входят: листы мультисекционные, с маркерами «x» и текстовой датой — отдельный пункт.

const (
	// vtbSuppSheet — лист-якорь квартального супердополнения: имя фиксировано («1.» — часть
	// имени), лист один. Месячные книги такого листа не несут, поэтому якорь разводит семьи
	// в диспетчере parseVtbBook без ложных совпадений.
	vtbSuppSheet = "1.Ключевые показатели"
)

// vtbSuppYtdRe / vtbSuppQtrRe — подписи колонок-периодов листа супердополнения: накопленная
// «9М'26» (M латинская принимается той же формой) и квартальная «3кв'26». Год двузначный —
// машинное именование колонок квартальной книги, в отличие от четырёхзначного года месячного
// листа P&L («август'2026»). Дата накопленной колонки — последний день её месяца N; квартальной —
// последний день 3N-го месяца (3кв'26 → 2026-09-30). Подписи «ИЗМЕНЕНИЕ» формам не соответствуют
// и колонками значений не становятся.
var (
	vtbSuppYtdRe  = regexp.MustCompile(`^(\d+)[МM]'(\d{2})$`)
	vtbSuppQtrRe  = regexp.MustCompile(`^(\d+)кв'(\d{2})$`)
	vtbSuppNoteRe = regexp.MustCompile(`\s*\(\d+\)$`)
)

// vtbSuppSeriesMap — литеральная карта «подпись строки листа «1.Ключевые показатели» → имя ряда»
// (спека §4.4, односторонний контракт §11.4). Ключи — подписи после нормализации vtbSeriesName
// (NBSP и переносы — в один пробел, служебный дефис подпункта отброшен) и снятия хвостовой сноски
// «(N)» («ПРОЧИЕ ОПЕРАЦИОННЫЕ ДОХОДЫ (1)» → «ПРОЧИЕ ОПЕРАЦИОННЫЕ ДОХОДЫ»); «(Н20.0)», «(NIM)»,
// «(90+)» — не сноски и входят в ключи целиком. Балансовые девять склеиваются с существующими
// месячными рядами: та же метрика, а квартальные даты месячные файлы не несут — конфликта ключа
// (name, date) не будет. Потоки и коэффициенты дают базовое имя: к нему проход добавляет суффикс
