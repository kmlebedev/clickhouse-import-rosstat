// vtbSuppColumn — колонка значений листа супердополнения: индекс ячейки, дата точек и суффикс
// имени ряда. Суффикс непуст у колонок-периодов (« (9М)», « (3кв)» — дословно из подписи) и пуст у
// колонок-дат (остатки и нормативы живут в рядах без суффикса — месячных или новых).
type vtbSuppColumn struct {
	col    int
	date   time.Time
	suffix string
}

// parseVtbSupplementBook — разбор квартального супердополнения: лист «1.Ключевые показатели»
// целиком, пять секций. Шапкой секции строку делит подпись периода («9М'26», «3кв'26») или
// серийный номер даты Excel в её ячейках; колонки «ИЗМЕНЕНИЕ» точек не дают. Строка с подписью,
// по которой нет значений, — заголовок секции или сноска и пропускается; значения без подписи —
// ошибка (§6.4): записать такие числа нечем. Подпись со значениями, которой нет в
// vtbSuppSeriesMap, — ошибка с подписью: молчаливый пропуск был бы потерянным рядом, а смена
// подписи источником лечится правкой карты. Значения — сырые ячейки через vtbFloat (запятая —
// десятичный разделитель, NaN/Inf отвергаются), пустая ячейка точкой не становится (§6.7).
// Ошибки называют таблицу — ей оборачивает parseVtbBook вызывающего уровня.
//
// Датовой шапкой считается только строка, чья подпись не именует ряд: значения остатков
// (млрд ₽) дают серийные номера в окне 2000–2100 (36884.3 ≈ 2000-12-31) и без этой защиты
// строка данных принялась бы за шапку и переписала колонки секции.
func parseVtbSupplementBook(xlsx *excelize.File) (points []vtbPoint, err error) {
	sheet, err := vtbSheet(xlsx, vtbSuppSheet)
	if err != nil {
		return nil, err
	}
	rows, err := xlsx.GetRows(sheet, excelize.Options{RawCellValue: true})
	if err != nil {
		return nil, fmt.Errorf("лист %q: чтение строк: %w", sheet, err)
	}
	var (
		cols    []vtbSuppColumn // колонки текущей секции; nil — до первой шапки
		headers int             // найденные шапки секций: по ним файл опознаётся целиком
	)
	for i, row := range rows {
		label := vtbSuppSeriesLabel(vtbCell(row, 0))
		_, known := vtbSuppSeriesMap[label]
		// 1. Периодная шапка: подписи «9М'26»/«3кв'26» в данных не встречаются.
		period, err := vtbSuppPeriodColumns(sheet, row)
		if err != nil {
			return nil, err
		}
		if period != nil {
			cols = period
			headers++
			continue
		}
		// 2. Датовая шапка — строка, чья подпись не именует ряд (единица «(млрд рублей)», «%»):
		// иначе серийные номера остатков в окне 2000–2100 сделали бы шапкой строку данных.
		if dates := vtbSerialColumns(row); len(dates) > 0 && !known {
			cols = make([]vtbSuppColumn, 0, len(dates))
			for _, c := range dates {
				cols = append(cols, vtbSuppColumn{col: c.col, date: c.date})
			}
			headers++
			continue
		}
		// 3. Данные и прочие строки — в колонках текущей секции.
		if cols == nil {
			continue // заголовок листа и строки выше первой шапки — не данные
		}
		if label == "" {
			if vtbSuppRowHasValues(row, cols) {
				return nil, fmt.Errorf("лист %q, строка %d: значения без подписи ряда", sheet, i+1)
			}
			continue
		}
		if !vtbSuppRowHasValues(row, cols) {
			continue // заголовок секции или сноска «(1) Без учета…»: значений нет — пропускаем
		}
		if !known {
			return nil, fmt.Errorf("лист %q, строка %d: подпись %q не найдена в карте супердополнений",
				sheet, i+1, label)
		}
		base := vtbSuppSeriesMap[label]
		for _, c := range cols {
			raw := vtbCell(row, c.col)
			if raw == "" {
				continue // пустая ячейка — не точка ряда (§6.7)
			}
			value, err := vtbFloat(raw)
			if err != nil {
				return nil, fmt.Errorf("лист %q, строка %d (%q): %w", sheet, i+1, base, err)
			}
			points = append(points, vtbPoint{Series: base + c.suffix, Date: c.date, Value: value})
		}
	}
	if headers == 0 {
		return nil, fmt.Errorf("лист %q: не найдена шапка секции (ни периодных подписей, ни колонок с датами)", sheet)
	}
	if len(points) == 0 {
		return nil, fmt.Errorf("лист %q: не дал ни одной точки", sheet)
	}
	return points, nil
}

// vtbSuppSeriesLabel — имя ряда-основы из подписи строки: нормализация vtbSeriesName (NBSP и
// переносы — в один пробел, служебный дефис подпункта отброшен) и снятие хвостовой сноски «(N)»
// перед поиском в карте. Подпись-прочерк — не имя ряда (vtbSeriesName).
func vtbSuppSeriesLabel(cell string) string {
	return vtbSuppNoteRe.ReplaceAllString(vtbSeriesName(cell), "")
}

// vtbSuppPeriodColumns — колонки-периоды шапки секции: ячейки с подписями «9М'26» (накопленная)
// и «3кв'26» (квартальная). Строка без ни одной такой подписи — не периодная шапка (nil, без
// ошибки): датовые шапки отличает вызывающий цикл. Невалидный период («13М'26») — ошибка с
// подписью: колонка без корректной даты точек не дала бы, а её потеря прошла бы молча (§6.4).
func vtbSuppPeriodColumns(sheet string, row []string) ([]vtbSuppColumn, error) {
	var cols []vtbSuppColumn
	for col := 1; col < len(row); col++ {
		raw := vtbCell(row, col)
		if m := vtbSuppYtdRe.FindStringSubmatch(raw); m != nil {
			column, err := vtbSuppPeriodColumn(sheet, raw, m[1], m[2], 1)
			if err != nil {
				return nil, err
			}
			column.col = col
			cols = append(cols, column)
			continue
		}
		if m := vtbSuppQtrRe.FindStringSubmatch(raw); m != nil {
			column, err := vtbSuppPeriodColumn(sheet, raw, m[1], m[2], 3)
			if err != nil {
				return nil, err
			}
			column.col = col
			cols = append(cols, column)
		}
	}
	return cols, nil
}

// vtbSuppPeriodColumn — колонка-период шапки секции: n единиц по monthsPerUnit месяцев каждая
// (накопленная «9М'26» — n месяцев с начала года, квартальная «3кв'26» — n кварталов). Дата точки
// — последний день отчётного месяца; суффикс имени ряда — подпись колонки до апострофа (« (9М)»,
// « (3кв)»). Номер периода вне допустимого диапазона — ошибка: колонка без корректной даты
// точек не дала бы, а её потеря прошла бы молча (§6.4).
func vtbSuppPeriodColumn(sheet, raw, n, yy string, monthsPerUnit int) (vtbSuppColumn, error) {
	num, err := strconv.Atoi(n)
	if err != nil {
		return vtbSuppColumn{}, fmt.Errorf("лист %q: подпись колонки %q: период %q не разобран: %w", sheet, raw, n, err)
	}
	if num < 1 || num*monthsPerUnit > 12 {
		return vtbSuppColumn{}, fmt.Errorf("лист %q: подпись колонки %q: период %q вне допустимого диапазона", sheet, raw, n)
	}
	year, err := strconv.Atoi(yy)
	if err != nil {
		return vtbSuppColumn{}, fmt.Errorf("лист %q: подпись колонки %q: год %q: %w", sheet, raw, yy, err)
	}
	suffix := " (" + strings.SplitN(raw, "'", 2)[0] + ")"
	return vtbSuppColumn{
		date:   vtbLastDayOfMonth(2000+year, time.Month(num*monthsPerUnit)),
		suffix: suffix,
	}, nil
}

// vtbSuppRowHasValues — есть ли в строке непустое значение в колонках секции: строка без подписи
// с значениями отвергается, а подпись без значений (заголовок секции, сноска) пропускается.
func vtbSuppRowHasValues(row []string, cols []vtbSuppColumn) bool {
	for _, c := range cols {
		if vtbCell(row, c.col) != "" {
			return true
		}
	}
	return false
}
