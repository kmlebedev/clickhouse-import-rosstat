// cbrBopEstName собирает имя ряда из имени кода и вида периода: «Товары: экспорт (месяц)» —
// вид идёт в имя, а не в колонку таблицы (спека §3.2). Имя собирает код, и его же видят каталог
// рядов (cbr/bop_meta.go) и разбор: второго источника правды для имён нет.
func cbrBopEstName(code, kind string) string {
	return code + " (" + kind + ")"
}

// cbrBopEstKindKnown — вид периода колонки описан каталогом рядов; неизвестный вид — ошибка
// разбора (стандарт §10.6: ряд, которого нет в каталоге, в витрину не попадает).
func cbrBopEstKindKnown(kind string) bool {
	for _, known := range cbrBopEstKinds {
		if known == kind {
			return true
		}
	}
	return false
}

// cbrBopEstImport разбирает лист «Оценка ПБ …»: 17 агрегатов по 14 колонок (спека §3.3).
// Подписи агрегатов ищутся последовательно, начиная с первой строки данных (порядок строк
// листа), — это и различает повторяющиеся «Экспорт»/«Импорт»; ненайденная ожидаемая подпись —
// ошибка с её текстом (стандарт §6.4), а посторонние строки между агрегатами молча
// пропускаются (§6.6). Пустая ячейка — не точка (§6.7), литеральный ноль — точка: в платёжном
// балансе ноль означает «сальдо нулевое», а не «данных не имеется» (например, сальдо счёта
// операций с капиталом) — отличие от cbr_int_rate_loans, где ноль в ячейке означает пропуск.
// Нечисловая ячейка и NaN/Inf — ошибка: ParseFloat принимает «NaN» молча, а точка с NaN
// отравила бы ряд (сравнения с NaN ложны, суммы — NaN).
func cbrBopEstImport(xlsx *excelize.File, batch driver.Batch) error {
	sheet, err := cbrBopSheetByPrefix(xlsx, cbrBopEstTable, cbrBopEstSheetPrefix)
	if err != nil {
		return err
	}
	rows, err := xlsx.GetRows(sheet, excelize.Options{RawCellValue: true})
	if err != nil {
		return fmt.Errorf("%s: лист «%s»: %w", cbrBopEstTable, sheet, err)
	}
	// Первая ожидаемая подпись — якорь первой строки данных; список агрегатов непуст по
	// объявлению, поэтому индекс 0 здесь есть всегда.
	layout, err := cbrBopSheetLayout(rows, cbrBopEstTable, sheet, cbrBopEstAggregates[0].Label)
	if err != nil {
		return err
	}
	// Подписи всех 17 агрегатов ищутся до первой записи: пропавшая в середине списка подпись —
	// ошибка структуры листа (стандарт §6.4), и после неё не должна быть записана ни одна точка —
	// частично разобранный выпуск хуже пустого, потому что выглядит успешным.
	rowIndexes := make([]int, len(cbrBopEstAggregates))
	searchFrom := layout.FirstDataRow
	for i, agg := range cbrBopEstAggregates {
		rowIndex := -1
		for j := searchFrom; j < len(rows); j++ {
			if len(rows[j]) > 0 && cbrBopSameLabel(rows[j][0], agg.Label) {
				rowIndex = j
				break
			}
		}
		if rowIndex < 0 {
			return fmt.Errorf("%s: лист «%s»: после строки %d не найдена ожидаемая подпись агрегата %q — источник изменил состав листа",
				cbrBopEstTable, sheet, searchFrom, agg.Label)
		}
		rowIndexes[i] = rowIndex
		searchFrom = rowIndex + 1
	}
	// Вид периода каждой колонки обязан быть описан каталогом (стандарт §10.6): колонка нового
	// вида создала бы ряд, которого нет в v_series_catalog, — агент MCP не понял бы его значения.
	for _, column := range layout.Columns {
		if !cbrBopEstKindKnown(column.Period.Kind) {
			return fmt.Errorf("%s: лист «%s», колонка %s: вид периода %q не описан каталогом рядов таблицы",
				cbrBopEstTable, sheet, cbrBopColumnName(column.Index), column.Period.Kind)
		}
	}
	count := 0
	for i, agg := range cbrBopEstAggregates {
		row := rows[rowIndexes[i]]
		for _, column := range layout.Columns {
			// Строка короче набора колонок данных — у остальных колонок ячеек нет; недостающая
			// ячейка равносильна пустой и точкой не становится (§6.7).
			if column.Index >= len(row) {
				continue
			}
			cell := strings.TrimSpace(row[column.Index])
			if cell == "" {
				continue
			}
			value, err := strconv.ParseFloat(cell, 64)
			if err != nil {
				return fmt.Errorf("%s: лист «%s», строка %q, колонка %s: значение %q: %w",
					cbrBopEstTable, sheet, agg.Label, cbrBopColumnName(column.Index), cell, err)
			}
			if math.IsNaN(value) || math.IsInf(value, 0) {
				return fmt.Errorf("%s: лист «%s», строка %q, колонка %s: значение %q не конечно (NaN/Inf)",
					cbrBopEstTable, sheet, agg.Label, cbrBopColumnName(column.Index), cell)
			}
			name := cbrBopEstName(agg.Code, column.Period.Kind)
			if err = batch.Append(name, column.Period.Date, value); err != nil {
				return fmt.Errorf("%s: ряд %q, %s: %w",
					cbrBopEstTable, name, column.Period.Date.Format("2006-01-02"), err)
			}
			count++
		}
	}
	if count == 0 {
		return fmt.Errorf("%s: лист «%s»: разбор не дал ни одной точки", cbrBopEstTable, sheet)
	}
	return nil
}

// cbrBopEst — оценка ключевых агрегатов платёжного баланса: таблица, DDL и разбор листа
// «Оценка ПБ …»; каталог рядов и витрину v_cbr_bop публикует шаблон через AfterImport. Оценка
// ЦБ ревизуется следующим выпуском, поэтому точка перезаписывается по ключу (name, date), а
// лист ищется по префиксу имени — дата выпуска в нём меняется. Сломанная шапка, пропавшая
// подпись агрегата и ноль точек — ошибка (fail-fast, стандарт §6.4): «0 rows» выглядели бы
// успешным прогоном, а 51 ряд остался бы без обновления молча.
var cbrBopEst = util.ClickHouseImport{
	TableName: cbrBopEstTable,
	CreateTable: []string{`CREATE TABLE IF NOT EXISTS %s (
			  name LowCardinality(String)
			, date Date
			, value Float64
		) ENGINE = ReplacingMergeTree ORDER BY (name, date);
	`},
	DataUrl:                cbrBopEstDataUrl,
	ImportFunc:             cbrBopEstImport,
	AfterImport:            afterCbrBop(cbrBopEstSeriesMeta),
	PublicationCountPoints: cbrBopEstCountPoints,
}

