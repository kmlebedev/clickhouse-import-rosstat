// mtForecastVintageNote — общее свойство всех 16 рядов (спека §3.7): значение — диапазон, каким его
// зафиксировал конкретный выпуск, а не последняя редакция прогноза. Без этой оговорки агент MCP
// прочитал бы строку выпуска как «прогноз ЦБ» вообще, а диапазон — как факт (спека §1).
const mtForecastVintageNote = " Значение — диапазон границ lo и hi, каким его зафиксировал выпуск" +
	" release_date (винтаж): это прогноз ЦБ, а не факт; следующий выпуск может пересмотреть границы;" +
	" у точечного прогноза lo = hi; читать вместе с meeting_date."

// mtForecastOrigin — шаблон origin: источник (у части заседаний та же таблица приходит в
// «Среднесрочном прогнозе» — он публикуется в день заседания) и строка таблицы. Адрес файла в
// origin не входит: <id> в пути меняется от выпуска к выпуску (source-report §5), и каталог
// пришлось бы править каждые три месяца.
const mtForecastOrigin = "ЦБ, „Комментарий к среднесрочному прогнозу“/„Среднесрочный прогноз“, " +
	"таблица „Табл 1“, строка „%s“"

// mtForecastIndicatorByLabel — дескриптор показателя по нормализованной подписи строки; ok=false,
// если строки нет в реестре 16 — разбор такую строку предупреждает и пропускает (спека §3.3,
// стандарт §6.6). Сравнение точное: подпись приходит уже нормализованной (mtForecastNormalizeLabel),
// и «почти совпало» здесь означало бы чужую метрику под знакомым кодом.
func mtForecastIndicatorByLabel(label string) (mtForecastIndicator, bool) {
	for _, indicator := range mtForecastIndicators {
		if indicator.Label == label {
			return indicator, true
		}
	}
	return mtForecastIndicator{}, false
}

// cbrMtForecastSeriesMeta — каталог 16 объявленных рядов (спека §3.7): source — cbr_mt_forecast,
// частота — годовая, series — код показателя. Ряд, которого нет в каталоге, агент прочитал бы без
// описания (стандарт §10.6), а ряд, которого нет в разборе, остался бы в каталоге пустым: состав
// реестра, каталога и разбора сверяется тестом в обе стороны (стандарт §11.4).
var cbrMtForecastSeriesMeta = mtForecastMeta()

// mtForecastMeta — каталог рядов по реестру показателей: Series = Code, Title и Unit — из реестра
// (единицы — дословно из таблицы §3.2 спеки), Origin — источник, таблица и строка источника,
// Description — что измеряет показатель (mtForecastDescriptions) плюс свойства диапазона и
// винтажа (mtForecastVintageNote, спека §3.7).
func mtForecastMeta() []util.SeriesMeta {
	meta := make([]util.SeriesMeta, 0, len(mtForecastIndicators))
	for _, indicator := range mtForecastIndicators {
		description := mtForecastDescriptions[indicator.Code]
		if mtForecastPeerCodes[indicator.Code] {
			description += mtForecastPeerNote
		}
		meta = append(meta, util.SeriesMeta{
			Source:      mtForecastSource,
			Series:      indicator.Code,
			Title:       indicator.Title,
			Unit:        indicator.Unit,
			Frequency:   mtForecastFrequency,
			Origin:      fmt.Sprintf(mtForecastOrigin, indicator.Label),
			Description: description + mtForecastVintageNote,
		})
	}
	return meta
}
