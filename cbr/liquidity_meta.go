// cbrLiquiditySeriesMeta — каталог 25 рядов: 14 дневных и 11 по периодам усреднения.
var cbrLiquiditySeriesMeta = func() []util.SeriesMeta {
	meta := make([]util.SeriesMeta, 0, len(cbrLiquidityDailySeries)+len(cbrLiquidityAvgSeries))
	add := func(kind string, series []string, frequency string, origin string) {
		for _, name := range series {
			info, ok := cbrLiquidityMetaTitles[name]
			if !ok {
				info = struct{ title, unit, description string }{title: name, unit: "млрд руб.", description: ""}
			}
			meta = append(meta, util.SeriesMeta{
				Source:      "cbr_liquidity",
				Series:      kind + "/" + name,
				Title:       info.title,
				Unit:        info.unit,
				Frequency:   frequency,
				Origin:      origin,
				Description: info.description,
			})
		}
	}
	add(cbrLiquidityKindDaily, cbrLiquidityDailySeries, "D",
		"cbr.ru/hd_base/bliquidity — таблица «Ликвидность банковского сектора», колонка по индексу (заголовок иерархический)")
	add(cbrLiquidityKindAvg, cbrLiquidityAvgSeries, "I",
		"cbr.ru/hd_base/BSliquidityMA — таблица периодов усреднения, колонка по индексу; дата — первый день периода")
	return meta
}()
