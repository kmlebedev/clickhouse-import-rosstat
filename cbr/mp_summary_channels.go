// mpRiskDezHeaderRe — абзац-заголовок дезинфляционного списка блока «Инфляционные риски»:
// «Основные дезинфляционные риски включают:» (23092026), «Основным дезинфляционным фактором
// является:» (07052026), «Дезинфляционные риски выражены слабо…» (06112024). Одного стема
// «дезинфляционн» мало: первый абзац блока говорит о преобладании проинфляционных рисков
// над «дезинфляционными» и не открывает список.
var mpRiskDezHeaderRe = regexp.MustCompile(
	`основн[а-яё]*\s+дезинфляционн|дезинфляционн[а-яё]*\s+(?:риск|фактор)[а-яё]*\s+(?:включают|является|выражены|выделены)`)

// mpChannelSplitRe — граница предложения: знак конца (.!?) и пробел после него; фрагмент
// режется сразу после знака (так дословная цитата сохраняет свою пунктуацию).
var mpChannelSplitRe = regexp.MustCompile(`[.!?]\s+`)

// mpChannelSentences разбивает нормализованный текст абзаца или пункта на предложения по
// правилу (?<=[.!?])\s+ — Go-RE2 lookbehind не поддерживает, поэтому граница ищется как
// «знак + пробелы», а фрагмент берётся до знака включительно. Пустые фрагменты
// отбрасываются. От mpSentences (Task 3) отличается намеренно: там границей считается
// только точка перед заглавной буквой — для решения и сигнала это точнее, а разметке каналов
// нужен простой сплит, зафиксированный контроллером в Task 4.
func mpChannelSentences(text string) []string {
	var out []string
	start := 0
	for _, loc := range mpChannelSplitRe.FindAllStringIndex(text, -1) {
		if piece := strings.TrimSpace(text[start : loc[0]+1]); piece != "" {
			out = append(out, piece)
		}
		start = loc[1]
	}
	if tail := strings.TrimSpace(text[start:]); tail != "" {
		out = append(out, tail)
	}
	return out
}

// mpChannelHits — сработал ли хотя бы один узор канала на тексте (уже в нижнем регистре).
func mpChannelHits(ch mpChannel, lowText string) bool {
	for _, re := range ch.Patterns {
		if re.MatchString(lowText) {
			return true
		}
	}
	return false
}

// tagMPChannels размечает один документ (все блоки одного резюме) по 11 каналам ЦБ:
//   - пункты списков блока «Инфляционные риски» → risk_pro/risk_dez по порядку: пункты до
//     абзаца-заголовка дезинфляционного списка — проинфляционные, после — дезинфляционные;
//     абзацы этого блока — только заголовки списков и сами цитатами не являются;
//   - предложения всех абзацев и пунктов остальных блоков (включая пункты «Основные
//     аргументы…» блока 5 — они несут утверждения по каналам) → prose.
//
// Внутри пункта/абзаца разметка идёт по предложениям: одно предложение может попасть в
// несколько каналов, повтор (Channel, Kind, Text) отбрасывается. Seq — сквозной номер
// фрагмента в порядке обхода документа (один и тот же номер у всех каналов одного фрагмента).
func tagMPChannels(blocks []mpSummaryBlock) []mpChannelMatch {
	var (
		out  []mpChannelMatch
		seq  int
		dez  bool // в блоке рисков: пройден заголовок дезинфляционного списка
		seen = make(map[mpChannelMatchKey]bool)
	)
	for _, b := range blocks {
		kind := mpKindProse
		if b.Block == mpBlockRisks {
			kind = mpKindRiskPro
			if b.Kind == mpKindParagraph {
				if mpRiskDezHeaderRe.MatchString(strings.ToLower(b.Text)) {
					dez = true
				}
				continue
			}
			if dez {
				kind = mpKindRiskDez
			}
		}
		for _, sent := range mpChannelSentences(b.Text) {
			seq++
			low := strings.ToLower(sent)
			for _, ch := range mpChannels {
				if !mpChannelHits(ch, low) {
					continue
				}
				key := mpChannelMatchKey{Channel: ch.Slug, Kind: kind, Text: sent}
				if seen[key] {
					continue
				}
				seen[key] = true
				out = append(out, mpChannelMatch{Channel: ch.Slug, Kind: kind, Seq: seq, Text: sent})
			}
		}
	}
	return out
}
