// проинфляционных рисков, пункт списка дезинфляционных рисков, предложение прозы.
const (
	mpKindRiskPro = "risk_pro"
	mpKindRiskDez = "risk_dez"
	mpKindProse   = "prose"
)

// mpBlockRisks — четвёртый блок резюме (mpSummaryBlocks[3]) с двумя списками рисков: только
// его пункты дают kind risk_pro/risk_dez, абзацы остальных блоков — prose.
const mpBlockRisks = "Инфляционные риски"

// mpChannel — канал ЦБ из реестра 11 каналов (docs/KEY_RATE_CHANNELS.md §3, спека §3.4):
// slug для хранения, русское имя канала, направление относительно инфляции и набор узоров.
// Узоры — по стемам, в нижнем регистре, применяются к нормализованному (normMPText) тексту,
// приведённому к нижнему регистру; именно поэтому в них нет «\w» (в RE2 это ASCII-класс,
// кириллицу он не покрывает) — вместо него [а-яё]*.
type mpChannel struct {
	Slug     string
	Title    string
	Sign     string
	Patterns []*regexp.Regexp
}

// mpChannelMatch — совпадение канала с дословным (нормализованным) фрагментом документа:
// канал, вид (risk_pro|risk_dez|prose), сквозной номер фрагмента по документу и текст.
type mpChannelMatch struct {
	Channel string
	Kind    string
	Seq     int
	Text    string
}

// mpChannelMatchKey — ключ дедупликации матчей внутри документа (Channel, Kind, Text):
// одно предложение может попасть в несколько каналов, но не в один канал дважды.
type mpChannelMatchKey struct {
	Channel string
	Kind    string
	Text    string
}

// mpRes компилирует набор узоров канала. Ошибка регулярки — паника на этапе вычисления
// пакетной переменной (сеть/init не затрагиваются): опечатка должна ронять тесты, а не
// молча терять канал на проде.
func mpRes(patterns ...string) []*regexp.Regexp {
	out := make([]*regexp.Regexp, 0, len(patterns))
	for _, p := range patterns {
		out = append(out, regexp.MustCompile(p))
	}
	return out
}

