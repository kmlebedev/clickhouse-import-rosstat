package cbr

import (
	"testing"
	"time"
)

// TestCbrBopParsePeriod: четыре формы подписи периода (спека §3.5) и привязка даты по виду
// (§3.4). Подписи взяты как есть — с переносами строк, пометкой «(оценка)» и хвостом «г.»:
// хелпер общий для обеих выгрузок платёжного баланса, и годовая форма, которой нет в оценке,
// нужна стандартным компонентам (cbr_bop_standard).
func TestCbrBopParsePeriod(t *testing.T) {
	for name, tc := range map[string]struct {
		label string
		kind  string
		date  string
	}{
		"месяц":                    {"июль \n2026 г.\n(оценка)", "месяц", "2026-07-31"},
		"месяц прошлого года":      {"апрель\n2025 г.", "месяц", "2025-04-30"},
		"февраль високосного года": {"февраль 2024 г.", "месяц", "2024-02-29"},
		"первый квартал":           {"I квартал \n2025 г. ", "квартал", "2025-03-31"},
		"второй квартал с оценкой": {"II квартал \n2026 г. \n(оценка)", "квартал", "2026-06-30"},
		"четвёртый квартал":        {"IV квартал 2025", "квартал", "2025-12-31"},
		"накопленный итог":         {"январь - июль \n2026 г.\n(оценка)", "накопленным итогом", "2026-07-31"},
		"итог за декабрь":          {"январь - декабрь 2025", "накопленным итогом", "2025-12-31"},
		"итог с длинным тире":      {"январь — июль 2025", "накопленным итогом", "2025-07-31"},
		"год":                      {"2025 г.", "год", "2025-12-31"},
		"год без хвоста":           {"1994", "год", "1994-12-31"},
	} {
		t.Run(name, func(t *testing.T) {
			want, err := time.Parse("2006-01-02", tc.date)
			if err != nil {
				t.Fatalf("тест: дата %q: %v", tc.date, err)
			}
			got, err := cbrBopParsePeriod(tc.label)
			if err != nil {
				t.Fatalf("cbrBopParsePeriod(%q): %v", tc.label, err)
			}
			if got.Kind != tc.kind {
				t.Errorf("cbrBopParsePeriod(%q): вид %q, want %q", tc.label, got.Kind, tc.kind)
			}
			if !got.Date.Equal(want) {
				t.Errorf("cbrBopParsePeriod(%q): дата %s, want %s", tc.label, got.Date.Format("2006-01-02"), tc.date)
			}
		})
	}
	// Неразобранные подписи — ошибка, а не период: «Справочно:» стоит в строке шапки над подписью
	// прошлого года (её снимает выбор подписи снизу вверх), итог обязан начинаться с января,
	// квартал — латинской римской цифрой с годом.
	for name, label := range map[string]string{
		"пустая подпись":        "",
		"«Справочно:»":          "Справочно:",
		"итог не с января":      "февраль - июль 2026",
		"квартал без года":      "II квартал",
		"кириллическая цифра":   "Х квартал 2026",
		"пятый квартал":         "V квартал 2026",
		"месяц без года":        "июль",
		"год и месяц вразнобой": "2026 июль",
		"подпись с посторонним": "II квартал 2026 года",
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := cbrBopParsePeriod(label); err == nil {
				t.Errorf("cbrBopParsePeriod(%q): ожидалась ошибка разбора", label)
			}
		})
	}
}
