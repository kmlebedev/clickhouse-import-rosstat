type seriesTemplate struct {
	Unit        string
	Frequency   string
	Origin      string
	Description string
	Label       string
}

func namedSeriesMeta(names []string, t seriesTemplate) []util.SeriesMeta {
	meta := make([]util.SeriesMeta, 0, len(names))
	for _, name := range names {
		meta = append(meta, util.SeriesMeta{
			Source:      cbrSource,
			Series:      name,
			Title:       name,
			Unit:        t.Unit,
			Frequency:   t.Frequency,
			Origin:      t.Origin + ", " + t.Label + " «" + name + "»",
			Description: t.Description,
		})
	}
	return meta
}

