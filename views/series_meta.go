// polyusSeriesMeta собирает описания рядов Полюса для общего каталога series_catalog.
//
// Источника два, и словари у них РАЗНЫЕ — в этом главная тонкость:
//
//   - релизы перечисляются в polyus.MetricNames() (словарь PDF-разбора из
//     polyus/metrics.go): gold_output, revenue, capex и т.д.;
//   - датапак перечисляется в polyusDatapackMetricNames — подписями строк листа
//     Sheet1, которые попадают в колонку name таблицы databook_polyus.
//
// Общих имён у списков нет: один разбор не должен притворяться источником имён
// для другого. Именно на этом и разошлась первая версия этой функции: датапак
// собирался циклом по релизному словарю, и все его ряды описывали имена, которых
// в датапаке не бывает (а 23 настоящих имени в каталоге отсутствовали). Обе
// половины закреплены тестами: релизная — сверкой с polyus.MetricNames(),
// датапак — сверкой с подписями самих данных (views/datapack_names_test.go).
//
// Порядок строк детерминирован (словарь релизов, затем список датапака, оба — в
// фиксированном порядке), чтобы повторный прогон не зависел от обхода map.
// Единицы релизных рядов берутся из polyus.MetricDefinitions() — того же словаря,
// из которого их берёт импортёр; у датапака колонки единиц в схеме нет, и единица
// там называлась в тексте описания.
func polyusSeriesMeta() []util.SeriesMeta {
	byName := make(map[string]polyus.MetricDefinition, len(polyus.MetricNames()))
	for _, def := range polyus.MetricDefinitions() {
		byName[def.Name] = def
	}

	rows := make([]util.SeriesMeta, 0, len(polyus.MetricNames())+len(polyusDatapackMetricNames))

	for _, name := range polyus.MetricNames() {
		rows = append(rows, util.SeriesMeta{
			Source:      polyusSource,
			Series:      name,
			Title:       polyusTitle(name),
			Unit:        byName[name].Unit,
			Frequency:   polyusReleaseFrequency,
			Origin:      polyusReleasesOrigin,
			Description: polyusMetricDescription[name],
		})
	}

	for _, name := range polyusDatapackMetricNames {
		unit := polyusDatapackUnits[name]
		if unit != "" {
			unit += " (" + polyusDatapackUnitNote + ")"
		} else {
			unit = polyusDatapackUnitNote
		}

		rows = append(rows, util.SeriesMeta{
			Source:      polyusDatapackSource,
			Series:      name,
			Title:       polyusDatapackTitle(name),
			Unit:        unit,
			Frequency:   polyusDatapackFrequency,
			Origin:      polyusDatapackOrigin,
			Description: polyusDatapackMetricDescription[name],
		})
	}

	return rows
}

