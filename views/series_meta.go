// polyusSeriesMeta собирает описания рядов Полюса для общего каталога series_catalog.
//
// Список релизных метрик берётся из polyus.MetricNames(), а не выписывается здесь:
// каталог и словарь парсера обязаны ходить парой, и метрика, добавленная в
// polyus/metrics.go, должна обнаружиться тестом на полноту
// (TestPolyusSeriesMetaCoversEveryMetric), а не остаться невидимой агенту.
//
// Ряды датапака идут отдельным источником (polyus_datapack) при том же списке имён:
// ключ каталога — (source, series), и одноимённые ряды двух источников описываются
// независимо, каждый со своим origin и описанием гранулярности.
//
// Порядок строк — релизы по словарю парсера, затем датапак по тому же словарю:
// порядок воспроизводим, чтобы повторный прогон не зависел от map, чей обход
// случаен. Единицы и заголовки — из polyus/metrics.go, где они уже заданы вместе
// с метрикой; колонка unit каталога должна совпадать с unit колонки витрины,
// и это ровно та единица.
func polyusSeriesMeta() []util.SeriesMeta {
	names := polyus.MetricNames()

	byName := make(map[string]polyus.MetricDefinition, len(names))
	for _, def := range polyus.MetricDefinitions() {
		byName[def.Name] = def
	}

	rows := make([]util.SeriesMeta, 0, 2*len(names))

	for _, name := range names {
		rows = append(rows, util.SeriesMeta{
			Source:      polyusSource,
			Series:      name,
			Title:       polyusTitle(name),
			Unit:        byName[name].Unit,
			Frequency:   polyusReleaseFrequency,
			Origin:      polyusReleasesOrigin,
			Description: polyusMetricDescription[name],
		})
	}

	for _, name := range names {
		rows = append(rows, util.SeriesMeta{
			Source:      polyusDatapackSource,
			Series:      name,
			Title:       polyusTitle(name) + ", по активам",
			Unit:        byName[name].Unit,
			Frequency:   polyusDatapackFrequency,
			Origin:      polyusDatapackOrigin,
			Description: polyusDatapackMetricDescription[name],
		})
	}

	return rows
}

