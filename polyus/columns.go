// infiniteX — внешняя граница крайних колонок: она не ограничена ничем, потому
// что за пределами шапки нет соседа, с которым можно поделить промежуток.
// Бесконечность заменена большим, но конечным числом: арифметика с Inf
// превратила бы середину промежутка в NaN, и covers перестал бы работать.
const infiniteX = 1e18

// maxPeriodTokens — самая длинная форма периода в шапке: «1 п/г 2026» —
// ровно те же три слова, что разбирает matchPeriodAt.
const maxPeriodTokens = 3

// Column — колонка таблицы, выведенная из координат шапки, а не из порядка слов.
//
// Left и Right — уже расширенные границы для covers: между соседними колонками
// граница проходит по середине промежутка между правым краем левой и левым
// краем правой, у крайних колонок внешняя граница бесконечна.
type Column struct {
	Period string // Формат: 2024FY или 2026H1; пусто у непериодной колонки
	Type   string // Тип: FY, H или Q; пусто у непериодной колонки
	Left   float64
	Right  float64
}

// covers сообщает, попадает ли X значения в колонку.
func (c Column) covers(left float64) bool {
	return left >= c.Left && left < c.Right
}

// columnsFromHeader выводит колонки таблицы из полосы шапки.
//
// Полоса, а не одна строка, потому что шапка реальных релизов разнесена по
// нескольким строкам: в 1H2026 подписи колонок и «$ млн» стоят на одном Top,
// а в FY2024 «$ mln (if not mentioned otherwise)» уехало на отдельную строку
// на 0.77pt выше подписей — при группировке по точному Top (штатный для
// расчёта режим) это две независимые строки, и по одной из них шапку не собрать.
//
// Слова всех строк полосы сливаются в одно координатное пространство и
// сортируются по Left: период и метка единиц измерения могут лежать на разных
// строках, а колонки — это интервалы по X, и их порядок задаёт только X.
//
// Прежде чем резать полосу на колонки, слова собираются в слоты (headerSlots):
// слово с одной строки может стоять НАД словом с другой, и тогда они делят
// одну колонку. Так устроена шапка релизов 4Q/FY 2019–2021: квартал «4Q» набран
// на строке подписей (top=306.99, x=228.10), а его год «2019» — на строке под
// ним (top=317.31, x=224.02). По отдельности ни то, ни другое периодом не
// является: «2019» читается как год, а «4Q» — как обрывок, который ещё и встаёт
// в слиянии по Left ВПЕРЁДИ своего года (224.02 < 228.10), так что простое
// слияние по X отдаёт кварталу чужой год и теряет половину колонок. Слот склеивает
// пару, и её разбор даёт полный период.
//
// Дальше идём по слотам слева направо, пробуя разбор окна: слот, уже опознанный
// как период (вертикальная пара), забирает окно целиком; иначе окно растёт от
// одного слота до maxPeriodTokens и берёт первый разобравшийся вариант — так
// «1 п/г 2026», разнесённое по трём словам одной строки, остаётся полугодием,
// а не годом. Резолвленный слот окно пересекать не может: иначе он приклеился бы
// к соседу и съел колонку изменения.
//
// Каждый слот, не вошедший в период, становится отдельной непериодной колонкой:
// без них колонки справа сдвинулись бы влево, а covers начал бы относить значения
// соседям. Границы колонок считаются после разбора, потому что промежуток до
// правого соседа известен только тогда.
func columnsFromHeader(headerLines []Line) []Column {
	slots := headerSlots(headerLines)
	if len(slots) == 0 {
		return nil
	}

	texts := make([]string, 0, len(slots))
	for _, slot := range slots {
		for _, word := range slot.words {
			texts = append(texts, word.Text)
		}
	}

	columns := make([]Column, 0, len(slots))

	for i := 0; i < len(slots); {
		if info := slots[i].period; info != nil {
			columns = append(columns, Column{
				Period: info.Period,
				Type:   info.Type,
				Left:   slots[i].left,
				Right:  slots[i].right,
			})

			i++

			continue
		}

		if column, width, ok := matchSlotWindow(slots, texts, i); ok {
			columns = append(columns, column)

			i += width

			continue
		}

		// Слот не начинает период: он определяет границу соседних колонок.
		columns = append(columns, Column{Left: slots[i].left, Right: slots[i].right})

		i++
	}

	return widenColumns(columns)
}

// headerSlot — единица разбора шапки: одно слово либо вертикально склеенная
// группа слов, стоящих друг над другом по X (разные Top, перекрывающиеся
// интервалы Left..Left+Width). left/right — границы группы, взятые по крайним
// словам; у одиночного слова это его собственная рамка.
type headerSlot struct {
	words  []Word
	left   float64
	right  float64
	period *PeriodInfo
}

// headerSlots сливает слова полосы в слоты.
//
// Основание слияния — ПЕРЕКРЫТИЕ по X, а не просто близость и не одинаковый Top:
// слова одной печатной строки перекрываться не должны, а слова разнесённой шапки
// делят колонку, потому что центрированы друг над другом. Проверка «разные Top»
// обязательна: без неё слиплись бы соседние слова одной строки, у которых широкое
// слово налезает на узкого соседа. Транзитивность (объединение наращивается, пока
// находится перекрывающийся с ним слой) нужна там, где столбец набран тремя
// строками: средний слой может не пересекаться с верхним, но пересекаться с уже
// добавленным нижним.
//
// Внутри слота слова упорядочены по Top — сверху вниз, как их читает человек;
// в этом порядке их текст и уходит в parsePeriod. Слоты упорядочены по Left
// левого края: колонки — это интервалы по X, и порядок задаёт только X.
//
// Слот из одного слова периодом не объявляется здесь: «1 п/г 2026» — это три
// отдельных слова одной строки, и разбирать их должно окно, а не слот.
func headerSlots(headerLines []Line) []headerSlot {
	words := bandWords(headerLines)
	if len(words) == 0 {
		return nil
	}

	used := make([]bool, len(words))

	groups := make([][]Word, 0, len(words))

	for i := range words {
		if used[i] {
			continue
		}

		members := []Word{words[i]}
		used[i] = true

		for grown := true; grown; {
			grown = false

			left, right := wordsSpan(members)

			for j := range words {
				if used[j] || !overlaps(words[j], left, right) || sameTop(members, words[j].Top) {
					continue
				}

				members = append(members, words[j])
				used[j] = true
				grown = true

				left, right = wordsSpan(members)
			}
		}

		sort.SliceStable(members, func(a, b int) bool { return members[a].Top < members[b].Top })

		groups = append(groups, members)
	}

	sort.SliceStable(groups, func(a, b int) bool {
		leftA, _ := wordsSpan(groups[a])
		leftB, _ := wordsSpan(groups[b])

		return leftA < leftB
	})

	slots := make([]headerSlot, 0, len(groups))

	for _, group := range groups {
		left, right := wordsSpan(group)

		slot := headerSlot{words: group, left: left, right: right}

		if len(group) > 1 {
			texts := make([]string, 0, len(group))
			for _, word := range group {
				texts = append(texts, word.Text)
			}

			if !windowHasChangeLabel(texts) {
				if info, err := parsePeriod(strings.Join(texts, " ")); err == nil {
					slot.period = &info
				}
			}
		}

		slots = append(slots, slot)
	}

	return slots
}

// matchSlotWindow ищет период в окне слотов начиная с i: перебирает ширины от
// одного слота до maxPeriodTokens, пропускает окна с подписью колонки изменения
// (windowHasChangeLabel) и берёт первый разобравшийся вариант — ровно те же
// правила, что и у matchPeriodAt, но единицей счёта служит слот, а не слово.
// Окно, накрывающее уже разобранный слот, не рассматривается: он занят периодом.
func matchSlotWindow(slots []headerSlot, texts []string, i int) (Column, int, bool) {
	start := 0
	for k := 0; k < i; k++ {
		start += len(slots[k].words)
	}

	for width := 1; width <= maxPeriodTokens && i+width <= len(slots); width++ {
		blocked := false
		tokens := 0

		for k := i; k < i+width; k++ {
			if slots[k].period != nil {
				blocked = true

				break
			}

			tokens += len(slots[k].words)
		}

		if blocked {
			break
		}

		window := texts[start : start+tokens]
		if windowHasChangeLabel(window) {
			continue
		}

		info, err := parsePeriod(strings.Join(window, " "))
		if err != nil {
			continue
		}

		last := slots[i+width-1]

		return Column{
			Period: info.Period,
			Type:   info.Type,
			Left:   slots[i].left,
			Right:  last.right,
		}, width, true
	}

	return Column{}, 0, false
}

// wordsSpan возвращает левый и правый края набора слов.
func wordsSpan(words []Word) (float64, float64) {
	left, right := words[0].Left, words[0].Left+words[0].Width

	for _, word := range words {
		if word.Left < left {
			left = word.Left
		}

		if end := word.Left + word.Width; end > right {
			right = end
		}
	}

	return left, right
}

// overlaps сообщает, что слово лежит НАД интервалом left..right — то есть делит
// с ним колонку.
//
// Одного касания краями мало: у FY2024 «(» (x=112.46..115.14, top=60.83) и «if»
// (x=115.10..118.58, top=61.60) перекрываются на 0.04pt — это совпадение кеглей,
// а не слой шапки, и склейка в слот «( if» разрезала промежуток перед первым
// периодом лишний раз. Настоящий слой перекрывает соседа почти целиком: у
// разорванных пар 2019 года квартал и год делят колонку с frac=1.000. Порог
// stackOverlapFraction отделяет одно от другого с большим запасом.
func overlaps(word Word, left, right float64) bool {
	overlap := minFloat(word.Left+word.Width, right) - maxFloat(word.Left, left)
	if overlap <= 0 {
		return false
	}

	return overlap >= stackOverlapFraction*word.Width
}

// stackOverlapFraction — доля ширины слова, которую должно занимать перекрытие,
// чтобы слово считалось слоем того же столбца. Настоящие слои дают 1.000, 0.832
// у обрывка метки единиц и 0.015 у случайного касания «(»/«if» — порог 0.5
// разводит их с двукратным запасом в обе стороны.
const stackOverlapFraction = 0.5

func minFloat(a, b float64) float64 {
	if a < b {
		return a
	}

	return b
}

func maxFloat(a, b float64) float64 {
	if a > b {
		return a
	}

	return b
}

// sameTop сообщает, что слово с таким Top уже есть в группе: два слова одной
// строки не могут лежать друг над другом, и перекрытие между ними — не слой
// шапки, а наложение широкого слова на узкого соседа.
func sameTop(words []Word, top float64) bool {
	for _, word := range words {
		if word.Top == top {
			return true
		}
	}

	return false
}

// bandWords сливает строки полосы шапки в один список слов, упорядоченный по
// Left. Слова копируются, а не переиспользуются: сортировка по Left переставила
// бы слова внутри строк, которые вызывающий код ещё использует (Task 5 ищет по
// ним строку метрики). Пустая, но не nil полоса возвращает пустой срез — у
// пустого заголовка нет колонок.
func bandWords(headerLines []Line) []Word {
	words := []Word{}
	for _, line := range headerLines {
		words = append(words, line.Words...)
	}

	sort.SliceStable(words, func(i, j int) bool {
		return words[i].Left < words[j].Left
	})

	return words
}

// widenColumns раздвигает границы колонок до середины промежутков между
// соседями: подпись колонки и значение под ней не совпадают по X (в 1H2026
// метка «2026» на x=282.05, а значение — на x=290.33, потому что числа
// выровнены по центру, а подписи по левому краю). Без расширения значение
// выпало бы из своей колонки.
//
// Крайние колонки расширяются наружу до бесконечности: вне шапки делить
// промежуток не с кем, а значение может уехать левее первой метки — так
// подпись строки метрики («Выручка») остаётся в первой колонке, а не считается
// значением периода.
//
// Границы считаются по исходным Left/Right всех колонок сразу: правка на месте
// сдвинула бы уже расширенный Right соседа и увела бы середину промежутка.
func widenColumns(columns []Column) []Column {
	// Ширина промежутка берётся из нерасширенных координат, поэтому правая
	// граница колонки запоминается до правки.
	rights := make([]float64, len(columns))
	for i, column := range columns {
		rights[i] = column.Right
	}

	for i := range columns {
		switch {
		case len(columns) == 1:
			columns[i].Left = -infiniteX
			columns[i].Right = infiniteX
		case i == 0:
			columns[i].Left = -infiniteX
			columns[i].Right = midpoint(rights[i], columns[i+1].Left)
		case i == len(columns)-1:
			columns[i].Left = midpoint(rights[i-1], columns[i].Left)
			columns[i].Right = infiniteX
		default:
			columns[i].Left = midpoint(rights[i-1], columns[i].Left)
			columns[i].Right = midpoint(rights[i], columns[i+1].Left)
		}
	}

	return columns
}

// midpoint возвращает середину промежутка между правым краем левой колонки и
// левым краем правой.
func midpoint(leftRight, rightLeft float64) float64 {
	return (leftRight + rightLeft) / 2
}

// lineText склеивает слова строки в текст через пробел — в том порядке, в каком
// они стоят на странице (слова Line уже упорядочены по Left).
func lineText(l Line) string {
	parts := make([]string, 0, len(l.Words))
	for _, w := range l.Words {
		parts = append(parts, w.Text)
	}

	return strings.Join(parts, " ")
}

// gluedLineText склеивает слова строки без разделителей. Нужен там, где
// словосочетание состоит из отдельных слов, а признак ищется по непрерывной
// строке: «$ млн» в TSV — это два слова, и только склейка даёт «$млн».
func gluedLineText(l Line) string {
	var glued strings.Builder
	for _, w := range l.Words {
		glued.WriteString(w.Text)
	}

	return glued.String()
}

// unitsMarkers — метки единиц измерения таблицы в проверенных релизах: русская
// («$ млн») и две английские — сокращённая («$ mln») и полная («$ million»).
// В TSV метка разбита на отдельные слова («$» + «млн»), поэтому ищется по
// склейке слов без разделителей.
var unitsMarkers = []string{"$млн", "$mln", "$million"}

// unitsMarker сообщает, что строка несёт метку единиц измерения таблицы.
//
// Именно она отличает финансовую таблицу от производственной: у производственной
// таблицы русского релиза 1H2026 (шапка на 206.51) метки единиц нет, и её колонки
// не должны обслуживать финансовые строки.
func unitsMarker(l Line) bool {
	glued := gluedLineText(l)

	for _, marker := range unitsMarkers {
		if strings.Contains(glued, marker) {
			return true
		}
	}

	return false
}

// isPeriodHeaderLine сообщает, что строка — строка шапки таблицы: она несёт не
// меньше двух непересекающихся меток колонок-периодов либо подписи колонок
// изменений.
//
// Порог в две метки отсекает строки данных: «Объем горной массы, тыс. м³
// 118 967 108 064 10%» походит на набор периодов («108 064»), но непересекающихся
// меток в ней меньше двух, и голый год заголовочной даты («1 2026» на 107.80
// русской страницы) тоже даёт одну метку. Шапка же всегда несёт минимум два
// периода — сравнивать больше нечего, если колонка одна.
//
// Метки периодов ищутся тем же разбором, что и в columnsFromHeader, и окно
// сдвигается на его ширину: иначе «1 п/г 2026» засчиталось бы трижды — как «1»,
// «1 п/г» и «1 п/г 2026».
func isPeriodHeaderLine(l Line) bool {
	text := lineText(l)
	for _, label := range changeLabels {
		if strings.Contains(text, label) {
			return true
		}
	}

	for _, marker := range unitsMarkers {
		if strings.Contains(gluedLineText(l), marker) {
			return true
		}
	}

	return countPeriodLabels(l) >= 2
}

// countPeriodLabels считает непересекающиеся метки периодов в строке — тем же
// разбором и с тем же сдвигом окна, что и columnsFromHeader.
func countPeriodLabels(l Line) int {
	texts := make([]string, 0, len(l.Words))
	for _, w := range l.Words {
		texts = append(texts, w.Text)
	}

	found := 0

	for i := 0; i < len(texts); {
		_, width, err := matchPeriodAt(texts, i, maxPeriodTokens)
		if err != nil {
			i++

			continue
		}

		found++

		i += width
	}

	return found
}

// changeLabels — подписи колонок изменений в проверенных отчётах. Колонка
// изменения стоит в шапке между периодами, и документ объявляет её сам; ищутся
// они в isPeriodHeaderLine.
var changeLabels = []string{"Изм. за", "Y-o-Y", "H-o-H", "y-o-y", "change"}

// changeLabelWords — слова, которыми набраны подписи колонок изменений.
// Отдельный список нужен разбору окон: подпись может состоять из нескольких
// слов («Изм. за год»), но окно периода не имеет права начинаться с любого из
// них.
var changeLabelWords = []string{"Изм.", "change", "y-o-y", "h-o-h"}

// isChangeLabelWord сообщает, что слово — часть подписи колонки изменения.
func isChangeLabelWord(text string) bool {
	for _, word := range changeLabelWords {
		if strings.EqualFold(text, word) {
			return true
		}
	}

	return false
}

// windowHasChangeLabel сообщает, что окно слов содержит подпись колонки
// изменения. Такое окно периодом быть не может: parsePeriod — матчер, а не
// валидатор, и в окне «change 2H 2014» он находит «2H 2014», забирая слово
// «change» себе. Для MD&A за 2014 год это стоило колонки изменения: её числа
// («3%» на x=416.11) попадали в колонку 2014H2 и выдавали себя за её значение.
func windowHasChangeLabel(window []string) bool {
	for _, text := range window {
		if isChangeLabelWord(text) {
			return true
		}
	}

	return false
}

// firstHeaderLine возвращает индекс первой строки-шапки финансовой таблицы или
// -1, если шапки на странице нет.
func firstHeaderLine(lines []Line) int {
	for i, l := range lines {
		if isTableHeader(l) {
			return i
		}
	}

	return -1
}

// isTableHeader сообщает, что строка открывает шапку финансовой таблицы: она
// несёт метку единиц измерения и размечает не меньше двух колонок-периодов.
//
// Одной метки единиц мало (её несёт и строка данных, случайно склеившая «$» и
// «млн»), одного набора периодов тоже мало (его даёт производственная таблица
// без метки единиц) — нужны оба признака. Два признака сразу дают ровно те
// строки, чьи колонки и обслуживают финансовые строки страницы.
func isTableHeader(l Line) bool {
	return unitsMarker(l) && isPeriodHeaderLine(l)
}

// headerBand возвращает полосу шапки, начинающуюся строкой lines[start]:
// саму строку и следующие за ней строки шапки.
//
// Полоса, а не одна строка, потому что шапка реальных релизов разнесена по
// нескольким строкам: в 1H2026 подписи колонок и «$ млн» стоят на одном Top,
// а в FY2024 «$ million (if not mentioned otherwise)» — на двух (60.83 и
// 61.60), потому что расшифровка набрана мельче. При группировке по точному
// Top это две независимые строки, и по одной из них шапку не собрать.
//
// Граница полосы — по РОЛИ строки, а не по зазору: полоса тянется вниз, пока
// каждая следующая строка сама является строкой шапки (isPeriodHeaderLine), и
// закрывается на первой, которая ею не является. Прежний критерий — разрыв по
// вертикали не больше headerContinuationGap (2pt) — не различал разорванную
// шапку релизов 4Q/FY 2019–2021: там шапка занимает три-четыре строки с
// зазорами 5.04pt (306.99 → 312.03) и 5.28pt (312.03 → 317.31) на фикстуре
// FY2019. По зазору полоса обрывалась на второй строке, подписи «4Q 2019» и
// «3Q 2019» не становились колонками, и 48 значений страницы оставались
// нераспределёнными. Роль строки от разрыва не зависит: строка с метками
// колонок остаётся строкой шапки на любом расстоянии.
//
// Между строками шапки может встать СТРОКА-ЗАПОЛНИТЕЛЬ — ни шапка, ни данные.
// В MD&A за 2014 год расшифровка метки единиц разорвана пополам и вторая её
// половина уехала ВНИЗ, под первую: «$ mln FY 2014 …» на 125.49, «(if not
// mentioned otherwise)» на 126.71, и только под ними — «change» на 132.45.
// Строка 126.71 не несёт ни меток колонок, ни чисел, и полоса, останавливающаяся
// на первой такой строке, теряет «change» вместе с его колонкой: числа колонки
// изменения («3%» на x=416.11) накрываются соседним периодом «2H 2014» и
// подменяют его значение. Поэтому на строке-заполнителе полоса не рвётся, а
// ЗАГЛЯДЫВАЕТ ВПЕРЁД и продолжается, если до первых данных встретит строку шапки
// (в 2014 это как раз «change»). Числа заглядывание не пропускает: любые данные
// на пути — уже не шапка.
//
// Полоса растёт и ВВЕРХ от якоря — но только на строку подписей кварталов.
// Якорь — строка с меткой единиц, и она не обязана быть самой верхней строкой
// шапки: у релизов 4Q/FY 2020 и 2021 метка единиц лежит на одной строке с
// подписями изменений и годами (top=81.59 и 220.79), а строка кварталов
// «4Q 3Q 4Q» стоит НАД ней (top=76.19 и 215.39). Голый «4Q» — не период:
// parsePeriod читает только «4Q 2020» и «4Q2020», поэтому строка кварталов не
// является ни строкой шапки, ни строкой данных. Без подъёма квартал не
// склеивается со своим годом на строке ниже, и «4Q 2020» с «3Q 2020» молча
// становятся годовыми колонками 2020FY — три разных значения под одним ключом.
//
// Подъём ограничен строкой, ВСЕ слова которой — обрывки периодов («4Q», «3Q»),
// а не любым заполнителем: у FY2019 над якорем стоит «Comparative financial
// results», у MD&A за 2014 — «Highlights», и полоса, тянущаяся вверх на любой
// заполнитель, съела бы соседнюю (производственную) шапку русской страницы и
// подпись «y-o-y». Дальше вверх полоса не идёт.
//
// Одного совпадения по словам мало: подъём обязан быть ПРИВЯЗАН к таблице по
// вертикали. Строка из одних обрывков периодов — это ещё и шапка СОСЕДНЕЙ
// таблицы: две таблицы, стоящие подряд без прозы между ними, дают ровно такую
// строку над чужим якорем («2H 1H» над шапкой следующей таблицы), и подъём без
// ограничения по расстоянию втянул бы её в полосу. Ошибка при этом молчаливая и
// хуже той, которую подъём лечит: значения остались бы те же, но годовая колонка
// получила бы ключ полугодия соседа (2024FY → 2024H2), и — в отличие от
// дубликата ключа — ни один тест на столкновение периодов такого не поймает.
// Поэтому подъём берётся, только если строка-обрывок прижата к якорю: разрыв не
// больше maxFragmentLiftGap.
//
// Порог измерен по фикстурам, а не подобран: у обоих настоящих случаев разрыв
// ровно 5.40pt (FY2020 76.19→81.59, FY2021 215.39→220.79), а ближайшая строка
// над якорем, которая обрывком периодов НЕ является, — «y-o-y» MD&A за 2014 на
// 7.07pt (её отсекает уже проверка по словам). Первый же реалистичный разрыв
// между таблицами — строка прозы и заголовок раздела на 18.18pt и больше
// (23.28–26.58 на прочих фикстурах). Порог 8pt отделяет 5.40 от 7.07 снизу
// (запас 1.5×) и от 18.18 сверху (запас 2.3×), не завися при этом от того, в
// каком block_num очутилась строка: у FY2020 и FY2021 шапка и строка кварталов
// лежат в РАЗНЫХ блоках, поэтому равенство блоков привязкой служить не может.
//
// Строка данных закрывает полосу ДО проверки роли: isPeriodHeaderLine может
// принять набор чисел с метками годов за строку шапки, и тогда полоса съела бы
// метрику — строка оказалась бы в шапке, а её значения не разобранными.
//
// При этом ни одна нынешняя фикстура проверку не нагружает: единственная строка,
// где сходятся ОБА признака (и шапка, и данные), — сам якорь (1H2026 на 369.26,
// FY2020 на 81.59, FY2021 на 220.79; на FY2019, FY2024 и MD&A за 2014 таких строк
// нет вовсе). Цикл начинает с start+1 и якорь повторно не проверяет, поэтому во
// время обхода isDataLine решающим сейчас не бывает ни разу.
//
// Проверка всё равно оставлена: она утверждает правило, а не подгоняется под
// фикстуры. Якорь русской страницы — это финансовая шапка, набранная в одну
// строку с меткой единиц, и он действительно «и шапка, и данные» сразу; стоит
// полосе когда-нибудь начать раньше (или вырасти назад, на строку с числами), и
// без этой проверки метрика молча уедет в шапку.
//
// Строка подписи колонки изменения (changeLabels) отдельной ветки не требует:
// isPeriodHeaderLine возвращает true на тех же подписях, и «change» из MD&A за
// 2014 год попадает в полосу как обычная строка шапки.
func headerBand(lines []Line, start int) []Line {
	band := []Line{lines[start]}

	for i := start + 1; i < len(lines); i++ {
		if isPeriodHeaderLine(lines[i]) && !isDataLine(lines[i]) {
			band = append(band, lines[i])

			continue
		}

		// Ни шапка, ни данные — строка-заполнитель. Полоса продолжается,
		// только если под ней ждёт строка шапки, а не данные.
		if isDataLine(lines[i]) || !headerLineFollows(lines, i+1) {
			break
		}
	}

	if start > 0 && isFragmentRowAbove(lines[start-1], lines[start]) {
		return append([]Line{lines[start-1]}, band...)
	}

	return band
}

// maxFragmentLiftGap — максимальный вертикальный разрыв между якорем и строкой
// обрывков периодов, при котором строка считается частью ЭТОЙ шапки. Измерено по
// фикстурам: настоящие случаи — 5.40pt, ближайшая прозаическая строка над якорем
// — 18.18pt. Подробнее в комментарии headerBand.
const maxFragmentLiftGap = 8.0

// isFragmentRowAbove сообщает, что строка above — часть шапки, начинающейся
// строкой anchor, а не соседней таблицы: она набрана только обрывками периодов и
// прижата к якорю по вертикали.
//
// Обе проверки нужны вместе. Только по словам подъём втянул бы в полосу шапку
// следующей таблицы (её строка подписей тоже состоит из «2H» и «1H»), а значения
// при этом остались бы на своих местах — молча сменился бы только ключ периода.
// Только по расстоянию — подъём схватил бы «y-o-y» MD&A за 2014 (7.07pt, но это
// не обрывок периода, а подпись колонки изменения).
//
// Разрыв берётся по модулю: строка выше обязана быть выше и по Top, и неотрицательный
// разрыв — это то, что проверяется; модуль защищает от молчаливого подъёма на
// строку, которая очутилась НИЖЕ якоря (порядок строк задаёт вызывающий, и
// полагаться на него здесь незачем).
func isFragmentRowAbove(above, anchor Line) bool {
	return math.Abs(anchor.Top-above.Top) <= maxFragmentLiftGap && isPeriodFragmentLine(above)
}

// isPeriodFragmentLine сообщает, что строка состоит только из обрывков периодов —
// подписей вроде «4Q» и «3Q», которые сами периодом не являются (parsePeriod
// читает лишь «4Q 2020»), но вместе с годом на соседней строке его образуют.
//
// Такая строка несёт не меньше двух обрывков: одиночное «4Q» — соринка вёрстки,
// а не строка подписей колонок, и поднимать на неё полосу незачем.
func isPeriodFragmentLine(l Line) bool {
	if len(l.Words) < 2 {
		return false
	}

	for _, w := range l.Words {
		if !rePeriodFragment.MatchString(w.Text) {
			return false
		}
	}

	return true
}

// rePeriodFragment — подпись колонки-квартала или полугодия без года: «4Q», «3Q»,
// «1H», «2H». Год к такой подписи приходит из слов соседней строки полосы.
var rePeriodFragment = regexp.MustCompile(`^[1-4][QH]$`)

// headerLineFollows сообщает, что первая значимая строка начиная с start —
// строка шапки: строки-заполнители пропускаются, на строке данных поиск
// прекращается.
//
// Значимой считается только строка, у которой есть роль. Строка-заполнитель —
// это ОБРЫВОК шапки: расшифровка метки единиц («(if not mentioned otherwise)»),
// подпись графика или оглавление перед таблицей. В фикстуре 1H2026 между шапкой
// (369.26) и первой строкой данных (396.40) стоят сразу два таких обрывка —
// «Операционные показатели» на 383.42 и одинокое «2» на 396.13, — и полоса,
// требующая строку шапки сразу за первым из них, потеряла бы «change» 2014 года
// (там между шапкой и ею ровно один обрывок).
func headerLineFollows(lines []Line, start int) bool {
	for i := start; i < len(lines); i++ {
		switch {
		case isDataLine(lines[i]):
			return false
		case isPeriodHeaderLine(lines[i]):
			return true
		}
	}

	return false
}

// isDataLine сообщает, что строка — строка данных таблицы: в ней опознана
// метрика и есть хотя бы одно число.
//
// Проверка чисел идёт по словам, а не по остатку строки после метки: остаток
// вернул бы и слова шапки, а признак нужен ровно один — есть ли в строке число
// вообще. Числом считается то, что разбирает parseNumericToken; одиночное слово
// «(2%)» из «1 287 1 311 (2%)» она разбирает, а группа тысяч, разбитая на два
// слова («1» и «287»), и так даёт число хотя бы на первом из них.
func isDataLine(l Line) bool {
	if _, _, ok := matchMetric(lineText(l)); !ok {
		return false
	}

	for _, w := range l.Words {
		if _, err := parseNumericToken(w.Text); err == nil {
			return true
		}
	}

	return false
}
