package polyus

import (
	log "github.com/sirupsen/logrus"
)

// knownKPIPeriods — периоды, которые parseKPIPage разбирает надёжно.
//
// Шапки KPI-таблиц Polyus содержат шесть колонок: отчётный период, период
// прошлого года, изменение за год (%), период второго полугодия прошлого года и
// изменение за полугодие. Слова «Изм. за год»/«Изм. за п/г» периодом не
// становятся (parsePeriod их не разбирает), поэтому parseKPIPage видит только
// три колонки-периода и кладёт процент изменения в слот второго полугодия:
// на релизе за 1 п/г 2026 золото «за 2025H2» получается равным -2, хотя это
// «(2%)» из колонки «Изм. за год».
//
// Отсюда список: это ровно те полугодия, для которых первым в шапке стоит
// отчётный период (у релиза за 1 п/г 2026 — 1 п/г 2026 и 1 п/г 2025). Различить
// «1 п/г» и «2 п/г» по разобранному тексту страницы нельзя — оба дают форму
// H, а номер полугодия в шапку попадает только вместе с токеном периода,
// который parseKPIPage не хранит.
//
// Второе полугодие предыдущего года появится здесь, когда в отчётах начнут
// публиковаться полугодовые релизы (2 п/г 2026) — тогда первым периодом шапки
// станет 2026H2, а вторым 2026H1; на свежих релизах этого ещё нет.
var knownKPIPeriods = map[string]bool{
	"2026H1": true,
	"2025H1": true,
}

// guardKPIRecords отбрасывает записи, чей период parseKPIPage не отличает от
// колонки-изменения (см. knownKPIPeriods), и возвращает оставшиеся записи
// вместе с числом отброшенных.
//
// Отбрасывается запись целиком, а не один её период: в подменённом слоте лежит
// процент изменения, а не значение показателя, и по одной лишь записи понять,
// что это, нельзя. Ошибка здесь односторонняя — отброшенное значение не попадает
// в витрину, тогда как принятое изменение выдало бы себя за данные отчёта.
//
// Ограничение: если подменённый период попадёт в knownKPIPeriods (например,
// в будущем периоды начнут порождать записи, где легитимно есть и 2026H1, и
// 2025H1), защита перестанет срабатывать. Пока такого отчёта нет ни одного:
// все включённые KPI-отчёты — полугодовые релизы за первое полугодие.
func guardKPIRecords(records []MetricRecord) (kept []MetricRecord, dropped int) {
	for _, record := range records {
		if knownKPIPeriods[record.Period] {
			kept = append(kept, record)
			continue
		}

		dropped++
		log.Debugf(
			"drop %s %s = %v: period is a change column, not a report period",
			record.Metric,
			record.Period,
			record.Value,
		)
	}

	return kept, dropped
}
