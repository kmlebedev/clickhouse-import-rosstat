package edisclosure

import (
	"context"

	"github.com/ClickHouse/clickhouse-go/v2/lib/driver"
	"github.com/kmlebedev/clickhouse-import-rosstat/util"
)

// edisclosureView — витрина документов карточек e-disclosure для MCP-агента
// (спека §5.6). Сырая edisclosure_documents агенту не выдаётся: запросы к ней
// обязаны использовать FINAL, и витрина делает это за агента. Документы — не
// числовые ряды, поэтому series_catalog не заводится, а смысл колонок
// компенсируется комментариями ниже. Версия документа читается парой
// (sha256, archive_key): sha256 — отпечаток содержимого, archive_key — объект
// винтажного архива, в котором эта версия сохранена ("" — архив выключен).
var edisclosureView = util.View{
	Name:   "v_edisclosure_documents",
	Tables: []string{edisclosureTable},
	Select: `SELECT ticker, company_id, section, doc_type, period, basis_date, publication_date,
       fileid, url, size_bytes, sha256, archive_key, first_seen, loaded_at
FROM edisclosure_documents FINAL`,
	Comment: "Документы карточек e-disclosure: бухгалтерская отчётность " +
		"(IFRS, RAS), списки аффилированных лиц, решения общих собраний и прочие раскрытия " +
		"эмитентов (PLZL, SBER, CHMF и др.). Одна строка — последняя версия документа: ключ " +
		"идентичности (ticker, section, fileid), поэтому витрина читается поверх FINAL и " +
		"историю версий не показывает. Версия содержимого — sha256; archive_key — ключ " +
		"объекта в винтажном архиве, где эта версия сохранена ('' — архив был выключен при " +
		"записи). period — отчётный период строкой как в источнике («2025», «2026, " +
		"6 месяцев»), а не дата; basis_date — дата составления/основания, publication_date — " +
		"дата публикации (NULL — в карточке пусто), first_seen — когда документ впервые " +
		"увидел конвейер и не равна дате публикации. Повторный прогон с неизменившимся " +
		"содержимым строку не переписывает.",
	Columns: map[string]string{
		"ticker":           "Биржевой тикер эмитента (PLZL, SBER, CHMF): карточка e-disclosure привязана к эмитенту. Вместе с section и fileid — ключ идентичности документа",
		"company_id":       "id карточки e-disclosure — технический идентификатор источника, не человекочитаемое имя и не часть ключа: тикер задаёт код, company_id — страницу источника",
		"section":          "Раздел карточки: IFRS и RAS — отчётность по стандартам, AFFILIATES — аффилированные лица, AGM — общие собрания и прочие раскрытия. Вместе с ticker и fileid — ключ идентичности документа",
		"doc_type":         "Тип документа из карточки источника (например, «Список аффилированных лиц», «Годовая консолидированная финансовая отчетность по МСФО или иным международно признанным стандартам»). Метаданные, а не часть ключа: смена типа под тем же fileid — повод перекачать документ",
		"period":           "Отчётный период как в источнике, строкой: «2025», «2026, 6 месяцев»; у части строк период записан датой (например, «31.12.2020»). Это текст, а не поле даты: приведение к дате — только через basis_date/publication_date",
		"basis_date":       "Дата составления/основания документа (DD.MM.YYYY источника), Nullable(Date); NULL — дата в карточке пуста. У отчётности обычно конец отчётного периода, у списков аффилированных лиц — дата составления",
		"publication_date": "Дата публикации документа на e-disclosure, Nullable(Date); NULL — дата в карточке пуста. Это дата публикации, а не дата составления и не first_seen",
		"fileid":           "Fileid из FileLoad.ashx — идентичность документа в источнике. Вместе с ticker и section — ключ идентичности: замена содержимого под тем же fileid строку не размножает (лечение — EDISCLOSURE_RECHECK=1), а новая версия в таблице не хранится — история в архиве",
		"url":              "Исходная ссылка на файл документа (FileLoad.ashx). Провенанс строки; адрес может меняться от карточки к карточке",
		"size_bytes":       "Фактический размер скачанного файла в байтах (UInt64), а не размер из карточки источника: по нему видно, что сохранено телом",
		"sha256":           "sha256 содержимого файла — версия документа. Одинаковый sha256 у повторного прогона значит «документ не изменился»; новая версия содержимого даёт новый sha256 и новый объект архива",
		"archive_key":      "Ключ объекта в винтажном архиве версий (edisclosure_documents/<sha16>_<name>): где сохранена именно эта версия. Пустая строка — архив был выключен при записи, история этой версии недоступна",
		"first_seen":       "Когда конвейер впервые увидел документ (ticker, section, fileid). Не дата публикации: документ мог быть опубликован раньше, а первый прогон импортёра — позже; при повторных прогонах значение сохраняется",
		"loaded_at":        "Время записи строки в таблицу — версия ReplacingMergeTree. Витрина читает FINAL: у ключа (ticker, section, fileid) остаётся строка с наибольшим loaded_at, то есть последняя записанная версия",
	},
}

// publishEdisclosureView — публикует витрину v_edisclosure_documents с
// комментариями таблицы и колонок. Вызывается на каждом прогоне, в том числе
// на no-op: сбой публикации витрины не должен застревать за гейтом данных
// (спека §5.3, шаг 3). util.CreateView сам пропускает витрину, пока исходной
// таблицы ещё нет.
func publishEdisclosureView(ctx context.Context, conn driver.Conn) error {
	_, err := util.CreateView(ctx, conn, edisclosureView)
	return err
}
