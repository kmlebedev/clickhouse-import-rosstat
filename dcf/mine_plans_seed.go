package dcf

// Сид LOM-планов Полюса: снимок публичных констант по активам.
//
// Отчётная база — Годовой обзор ПАО «Полюс» за 2025 год
// (https://polyus.com/upload/iblock/d6b/godovoy_obzor_pao_polyus_za_2025_god.pdf)
// плюс презентация «Ключевые проекты роста» (декабрь 2024,
// https://polyus.com/upload/iblock/f13/klyuchevye_proekty_rosta.pdf). Год отчёта
// назван здесь, а не в каждом поле, потому что именно он делает снимок
// проверяемым: читатель может открыть тот же PDF и сверить числа.
const (
	// reportingYearBase — последний ПОЛНЫЙ отчётный год: 2025-й. План стартует с
	// него, а не с года прогона, иначе пересчёт NAV в январе сдвигал бы весь
	// горизонт на год вперёд и подменял факт прогнозом.
	reportingYearBase uint16 = 2025

	// groupTCC2025USDPerOz / groupAISC2025USDPerOz — общие денежные затраты и
	// совокупные затраты на производство и поддержание Группы за 2025 год
	// (Годовой обзор 2025, стр. 31: TCC $739; там же AISC $1 437).
	//
	// AISC по активам Полюс не публикует — раскрыт только групповой AISC. Поэтому
	// per-asset AISC здесь DERIVED: TCC актива плюс групповой клин. Это допущение,
	// а не факт, и оно помечено как derived в docs/DCF_DATA_COVERAGE.md.
	groupTCC2025USDPerOz  = 739.0
	groupAISC2025USDPerOz = 1437.0

	// sustainingWedgeUSDPerOz — клин «поддержание производства»: AISC минус TCC.
	// 1 437 − 739 = 698 USD/oz.
	//
	// Почему клин берётся из отчёта 2025 года, а не из более ранней версии: он
	// эскалирует TCC до AISC в каждом году плана, и при занижении клина NPV
	// систематически завышается на весь LOM — тем сильнее, чем длиннее горизонт
	// (Наталка 24 года, Сухой Лог 10). Старое значение 384 относилось к 2024 году,
	// когда надбавка к НДПИ ещё не действовала с января 2025-го.
	sustainingWedgeUSDPerOz = groupAISC2025USDPerOz - groupTCC2025USDPerOz
)

// assetPlanSeed — LOM-план одного актива до развёртки по годам: константы,
// которые Полюс публикует (срок службы, TCC, capex проекта и поддержания), плюс
// форма профиля производства.
//
// Развёртка в []MinePlanYear — отдельный шаг (buildPlanYears): здесь нет ни года
// с ценой, ни склейки с фактом добычи из databook_polyus, поэтому сид остаётся
// чистыми данными без обращения к БД и покрывается офлайн-тестом.
//
// Единицы те же, что у колонок mine_plans в ARCHITECTURE.md §6.2 (таблица полей
// DDL) и продублированы в прозе §6.4: production_koz — тыс. унций, TCC — USD/унц,
// capex и закрытие — млн USD. Смешение единиц даёт NPV, ошибочный в тысячи раз,
// поэтому юниты названы и в именах полей, и в комментариях к ним.
type assetPlanSeed struct {
	// Company — эмитент, которому принадлежит актив (PLZL). Поле оставлено
	// строкой, а не константой: модель считает NAV группы, и при появлении
	// второго эмитента его активы не должны требовать правки структуры.
	Company string
	// Asset — ключ, ПОЛНЫЙ аналог значения asset в databook_polyus
	// (VERNINSKOYE2 с двойкой, `Sukhoi Log` с пробелом и смешанным регистром).
	// Task 5 читает по нему факт добычи, поэтому расхождение здесь означало бы
	// молча пропущенный актив с warn вместо строк.
	Asset string
	// MineLifeYears — остаток срока службы месторождения по планам горных работ
	// (Годовой обзор 2025, стр. 115, примечание 3.7). Для Сухого Лога — длина
	// ProductionProfile: публичный горизонт первых 10 лет.
	MineLifeYears int
	// BaseYear — первый год плана в календаре. 2025 — последний полный факт;
	// горизонт идёт BaseYear..BaseYear+MineLifeYears-1.
	BaseYear uint16
	// TCC — общие денежные затраты актива, USD/унц (Годовой обзор 2025, стр. 5 и
	// стр. 31). Для активов без собственного раскрытия — прокси бизнес-юнита.
	TCC float64
	// CapexSustaining — капитальные затраты на поддержание производства в год,
	// млн USD. Вход сида: развёртка кладёт эту сумму в каждый год плана, потому
	// что Полюс не публикует split sustaining/project по активам.
	CapexSustaining float64
	// ClosureCosts — хвост рекультивации, млн USD, ОТРИЦАТЕЛЬНЫЙ (отток) в
	// последнем году LOM. Публичного per-asset раскрытия нет: поле заполняется
	// распределением группового провижена и помечено как допущение.
	//
	// ⚠ 0 здесь означает «не опубликовано по активу / не задано», и НИКОГДА — «затрат
	// на закрытие нет»: закрытие рудника не бесплатно (см. комментарий к
	// polyusAssetPlans). Потребитель (buildPlanYears) ОБЯЗАН трактовать 0 как
	// отсутствующий вход и не подставлять его как измеренный ноль; иначе NPV
	// завышается на приведённую стоимость хвоста. Величина не может «выглядеть
	// посчитанной»: подставлять сюда ноль как реальное значение запрещено
	// контрактом поля, пока распределение группового провижена не утверждено.
	ClosureCosts float64
	// ProjectCapex — единовременные капитальные затраты проекта, млн USD.
	// Ненулевой только у Сухого Лога: у действующих активов весь capex идёт в
	// поддержание.
	ProjectCapex float64
	// ProfileStartYear — первый год ПРОИЗВОДСТВА для активов, которых ещё нет в
	// факте (Сухой Лог). Ноль — актив уже производит, и план стартует с BaseYear.
	ProfileStartYear uint16
	// ProductionProfile — погонная добыча, тыс. унц/год, для активов без факта в
	// databook_polyus: длины профиля хватает, чтобы не читать БД там, где её нет.
	// Пустой профиль — профиль не задан, база берётся из факта.
	ProductionProfile []float64
	// HaltFrom/HaltTo — годы консервации карьера, ВКЛЮЧИТЕЛЬНО, когда добыча
	// равна нулю, но строка года сохраняется. Нули — консервации нет.
	HaltFrom uint16
	HaltTo   uint16
}

