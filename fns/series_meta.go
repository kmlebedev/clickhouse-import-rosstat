// fnsBudgetRevenueSeriesMeta — каталог всех рядов импортёра, выведенный из таблицы
// объявленных колонок: ряд, который разбирается, описан; ряда, которого нет в
// таблице колонок, в каталоге не появится (стандарт §10.6).
func fnsBudgetRevenueSeriesMeta() []util.SeriesMeta {
	meta := make([]util.SeriesMeta, 0, len(fnsSeriesRows))
	for _, row := range fnsSeriesRows {
		level := row.fnsLevel()
		phrase := fnsLevelPhrases[level.name]
		column := row.code
		if level.suffix != "1" {
			column = fmt.Sprintf("%s.%s", row.code, level.suffix)
		}
		description := fnsYtdNote + phrase.note + fnsNegativeNote + fnsGapNote + fnsScopeNote
		if extra, ok := fnsSeriesExtra[row.series()]; ok {
			description += extra
		}
		meta = append(meta, util.SeriesMeta{
			Source: fnsSource,
			Series: row.series(),
			Title:  fmt.Sprintf("%s — %s (1-НМ, накопленным итогом с начала года)", row.title, phrase.title),
			Unit:   fnsUnit,
			// Частота наблюдения — месячная, хотя публикуется накопленное: см. description.
			Frequency: "M",
			Origin: fmt.Sprintf("nalog.gov.ru, форма № 1-НМ, архив 1nm<as-of>reg.zip, лист "+
				"«11О Поступление налогов по территориям», код строки %s", column),
			Description: description,
		})
	}
	return meta
}
